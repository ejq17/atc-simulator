import { useSimStore } from '../store/simStore';
import { formatZulu } from '../lib/format';
import { Btn, LABEL } from '../components/ui';
import { Drawer } from './Drawer';

export function AtisDrawer({ onClose }: { onClose: () => void }) {
  const atis = useSimStore((s) => s.atis);
  const session = useSimStore((s) => s.session);
  const weatherNote = useSimStore((s) => s.weatherNote);
  useSimStore((s) => s.rev);
  if (!atis || !session) return null;
  const st = session.engine.getState();
  return (
    <Drawer title={`ATIS information ${atis.phonetic}`} onClose={onClose} width="min(540px,96vw)" testId="atis-drawer">
      <div className="flex flex-col gap-4 p-4">
        <div className="flex items-center justify-between gap-3">
          <span className="border border-atc-amber px-2 py-1 font-sans text-[11px] font-semibold uppercase tracking-wider text-atc-amber" data-testid="atis-simulated">{atis.simulatedLabel}</span>
          <span className="text-[11px] text-atc-muted">Issued {formatZulu(session.startUtcMs, atis.issuedAtSec)} · {atis.timeZulu}Z</span>
        </div>
        <p className="border-l-2 border-atc-cyan bg-atc-bg p-3 text-[13px] leading-relaxed text-atc-text" data-testid="atis-text">{atis.text}</p>
        <div className="flex gap-2">
          <Btn tone="cyan" onClick={() => session.speakAtis()} data-testid="atis-listen">▶ Listen</Btn>
          <Btn onClick={() => session.stopSpeaking()}>■ Stop</Btn>
        </div>
        <dl className="grid grid-cols-2 gap-3 text-[12px]">
          <div><dt className={LABEL}>Landing</dt><dd>{atis.activeRunways.landing.join(', ') || '—'}</dd></div>
          <div><dt className={LABEL}>Departing</dt><dd>{atis.activeRunways.departing.join(', ') || '—'}</dd></div>
          <div className="col-span-2"><dt className={LABEL}>Weather source</dt><dd className="break-words text-atc-muted">{weatherNote || st.weather.source}</dd></div>
        </dl>
        <p className="text-[11px] leading-snug text-atc-muted">
          This ATIS is generated by the simulator from the current weather and runways. It is not the real KACY broadcast and must not be used for any real-world purpose. The letter advances when wind, altimeter, visibility, ceiling or runways change enough to matter.
        </p>
      </div>
    </Drawer>
  );
}
